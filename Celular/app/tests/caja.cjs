const ts = require('typescript');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const codigo = ts.transpileModule(fs.readFileSync('src/app/nucleo/caja.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const modulo = { exports: {} }; new Function('exports', 'module', codigo)(modulo.exports, modulo);
const { calcularCaja } = modulo.exports;
const hoy = new Date(2026, 9, 16);
const cobro = (id, monto, mes=9, dia=15, inicial=false) => ({id, monto, fecha:new Date(2026,mes,dia), concepto:id, inicial});
const caja = {hasta:'2026-10-16', egresosPorMes:{'2026-09':200000,'2026-10':400000}, gastosIncluidos:[]};
assert.equal(calcularCaja([cobro('quincena',1500000)],caja,'2026-10',hoy).saldo,1100000);
assert.equal(calcularCaja([cobro('quincena',1500000),cobro('futura',1500000,9,30)],caja,'2026-10',hoy).saldo,1100000);
assert.equal(calcularCaja([cobro('anterior',1000000,8),cobro('quincena',1500000)],caja,'2026-10',hoy).saldo,1900000);
assert.equal(calcularCaja([cobro('anterior',1000000,8),cobro('saldo',500000,9,1,true),cobro('quincena',1500000)],caja,'2026-10',hoy).saldo,1600000);
assert.equal(calcularCaja([cobro('saldo',0,9,1,true)],caja,'2026-10',hoy).saldo,-400000);
assert.equal(calcularCaja([],caja,'2026-10',hoy).confirmado,false);
assert.equal(calcularCaja([cobro('septiembre',1000000,8)],caja,'2026-09',hoy).saldo,800000);
assert.equal(calcularCaja([cobro('septiembre',1000000,8),cobro('quincena',1500000)],caja,'2026-10',hoy).saldo,1900000);
console.log('8 casos de caja correctos: quincenas, pagos futuros, saldo inicial, cierre mensual y arrastre.');

const { ajusteGastos } = modulo.exports;
const base = { gastosIncluidos: [{id:'a',monto:100}] };
assert.equal(ajusteGastos(base,[{id:'a',monto:100,tarjetaId:null}]),0);
assert.equal(ajusteGastos(base,[{id:'a',monto:100,tarjetaId:null},{id:'nuevo',monto:50,tarjetaId:null}]),50);
assert.equal(ajusteGastos({gastosIncluidos:[{id:'a',monto:100},{id:'nuevo',monto:50}]},[{id:'a',monto:100,tarjetaId:null},{id:'nuevo',monto:50,tarjetaId:null}]),0);
assert.equal(ajusteGastos(base,[]),-100);
assert.equal(ajusteGastos(base,[{id:'a',monto:125,tarjetaId:null}]),25);
assert.equal(ajusteGastos(base,[{id:'a',monto:100,tarjetaId:1}]),-100);
console.log('6 casos de sincronización correctos: nuevo, sincronizado, borrado, editado y cambio a tarjeta.');
const cajaCredito = {hasta:'2026-10-16',egresosPorMes:{},gastosIncluidos:[]};
const nominal = calcularCaja([cobro('quincena',1500000)],cajaCredito,'2026-10',hoy).saldo;
assert.equal(nominal - ajusteGastos(cajaCredito,[{id:'compra',monto:200000,tarjetaId:1}]),1500000);
assert.equal(calcularCaja([cobro('quincena',1500000)],{...cajaCredito,egresosPorMes:{'2026-10':200000}},'2026-10',hoy).saldo,1300000);
assert.equal(nominal - ajusteGastos(cajaCredito,[{id:'compra',monto:200000,tarjetaId:null}]),1300000);
console.log('OK Compra con tarjeta: efectivo intacto. Pago de tarjeta o compra sin tarjeta: descuenta efectivo.');
