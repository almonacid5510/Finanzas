const ts = require('typescript');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const codigo = ts.transpileModule(fs.readFileSync('src/app/nucleo/nomina.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
const modulo={exports:{}};new Function('exports','module',codigo)(modulo.exports,modulo);
const {pagosNomina,validarNomina,recordatoriosNomina}=modulo.exports;
const plan={frecuencia:'Quincenal',dias:'5,20',diaSemana:1,fechaBase:'2026-09-25',montoPorPago:3200000,confirmada:true};
assert.deepEqual(pagosNomina(plan,'2026-10').map(p=>p.fecha),['2026-10-05','2026-10-20']);
assert.equal(pagosNomina({...plan,dias:'15,31'},'2027-02')[1].fecha,'2027-02-28');
const feb=pagosNomina({...plan,dias:'30,31'},'2027-02');assert.equal(feb.length,2);assert.notEqual(feb[0].id,feb[1].id);
assert.equal(pagosNomina({...plan,frecuencia:'Mensual',dias:'31'},'2028-02')[0].fecha,'2028-02-29');
assert.deepEqual(pagosNomina({...plan,frecuencia:'Cada 14 días'},'2026-10').map(p=>p.fecha),['2026-10-09','2026-10-23']);
assert.ok(pagosNomina({...plan,frecuencia:'Semanal',diaSemana:5},'2026-10').every(p=>new Date(p.fecha+'T00:00:00').getDay()===5));
assert.deepEqual(pagosNomina({...plan,frecuencia:'Variable'},'2026-10'),[]);
assert.deepEqual(pagosNomina({...plan,confirmada:false},'2026-10'),[]);
assert.throws(()=>validarNomina({...plan,dias:'15,15'}));
assert.throws(()=>validarNomina({...plan,montoPorPago:0}));
assert.throws(()=>validarNomina({...plan,dias:'0xF,20'}));
assert.deepEqual(pagosNomina({...plan,dias:'5,20,'},'2026-10').map(p=>p.fecha),['2026-10-05','2026-10-20']);
console.log('12 casos correctos: fechas personalizadas, meses cortos, frecuencia semanal, cada 14 días, variables y validación.');

const mensual = {...plan, frecuencia:'Mensual', dias:'15'};
const pendientes = (hoy, cobrados=[], pospuestos={}, meses=['2026-10']) => recordatoriosNomina(mensual,meses,cobrados,pospuestos,hoy);
assert.equal(pendientes('2026-10-14').length,0,'No recuerda antes de la fecha');
assert.equal(pendientes('2026-10-15').length,0,'No recuerda el mismo día');
assert.equal(pendientes('2026-10-16').length,1,'Recuerda desde el día siguiente');
const pago = pendientes('2026-10-16')[0];
assert.equal(pendientes('2026-10-16',[pago.id]).length,0,'Un pago recibido no vuelve a recordarse');
assert.equal(pendientes('2026-10-16',[],{[pago.id]:'2026-10-17'}).length,0,'Posponer oculta el aviso durante el día');
assert.equal(pendientes('2026-10-17',[],{[pago.id]:'2026-10-17'}).length,1,'Reaparece mañana');
assert.equal(pendientes('2026-10-18',[],{[pago.id]:'2026-10-17'}).length,1,'Si no abrió mañana, aparece al regresar');
assert.equal(pendientes('2026-10-17',[],{[pago.id]:'2026-10-18'}).length,0,'Se puede posponer más de una vez');
assert.deepEqual(pendientes('2026-10-16',[],{},['2026-10','2026-11']).map(p=>p.fecha),['2026-10-15'],'No inventa pagos de meses anteriores al inicio');
assert.equal(recordatoriosNomina({...mensual,dias:'31'},['2026-12','2027-01'],[],{},'2027-01-01')[0].fecha,'2026-12-31','Cruce de mes y año');
assert.equal(recordatoriosNomina({...mensual,dias:'31'},['2027-02','2027-03'],[],{},'2027-03-01')[0].fecha,'2027-02-28','Día siguiente a febrero corto');
assert.equal(recordatoriosNomina({...mensual,frecuencia:'Variable'},['2026-10'],[],{},'2026-10-16').length,0,'Variable no genera recordatorios sin fecha');
const dos = recordatoriosNomina({...plan,dias:'5,15'},['2026-10'],[],{},'2026-10-16');
assert.equal(dos.length,2);assert.ok(dos[0].fecha<dos[1].fecha,'Primero pregunta el pago más antiguo');
assert.equal(recordatoriosNomina({...plan,dias:'5,15'},['2026-10'],[],{[dos[0].id]:'2026-10-17'},'2026-10-16')[0].id,dos[1].id,'Posponer un pago no oculta los demás');
assert.equal(recordatoriosNomina(mensual,['2026-10','2026-10'],[],{},'2026-10-16').length,1,'No duplica avisos');
console.log('16 verificaciones correctas de recordatorios: día siguiente, confirmación, posponer, regreso, meses cortos e inicio del historial.');

assert.deepEqual(modulo.exports.FRECUENCIAS_NOMINA,['Mensual','Quincenal','Semanal'],'Solo se ofrecen las tres frecuencias solicitadas');
